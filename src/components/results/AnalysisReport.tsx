import React, { useState } from 'react';
import {
  ShieldAlert,
  ShieldCheck,
  AlertTriangle,
  HelpCircle,
  Copy,
  Check,
  Printer,
  RotateCcw,
  Sparkles,
  Info,
  ExternalLink,
  CheckCircle2,
  ChevronRight,
  Layers,
  ArrowRight,
} from 'lucide-react';
import { AnalysisResult } from '../../types/analysis';
import { RiskMeter } from './RiskMeter';
import { HeatmapViewer } from '../forensics/HeatmapViewer';
import { getRiskBadgeClasses } from '../../services/riskEngine';

interface AnalysisReportProps {
  result: AnalysisResult;
  uploadedImageUrl?: string | null;
  onReset: () => void;
}

export const AnalysisReport: React.FC<AnalysisReportProps> = ({
  result,
  uploadedImageUrl,
  onReset,
}) => {
  const [copied, setCopied] = useState(false);
  const badgeConfig = getRiskBadgeClasses(result.riskLevel);

  const handleCopyReport = () => {
    const textReport = `--- SCAM SHIELD FORENSIC REPORT ---
Target: ${result.targetSummary}
Platform: ${result.platform}
Risk Score: ${result.riskScore}/100 (${result.riskLevel})
Category: ${result.category}
Verdict: ${result.verdictLabel}

THREAT SIGNALS DETECTED:
${result.threatSignals.map((s) => `• [${s.severity.toUpperCase()}] ${s.title}: ${s.description}`).join('\n')}

WHAT WE DETECTED:
${result.explanation.whatWeDetected.map((w) => `• ${w}`).join('\n')}

WHY IT MATTERS:
${result.explanation.whyItMatters}

RECOMMENDATIONS:
${result.recommendations.map((r) => `1. ${r}`).join('\n')}

Generated by Scam Shield (AI Cybersecurity Forensics)`;

    navigator.clipboard.writeText(textReport);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="space-y-6 max-w-5xl mx-auto my-6 animate-in fade-in slide-in-from-bottom-3 duration-300">
      
      {/* Demo Analysis Warning Banner if applicable */}
      {result.isDemo && (
        <div className="p-3.5 rounded-xl bg-amber-950/50 border border-amber-500/50 flex items-center justify-between text-xs text-amber-200">
          <div className="flex items-center space-x-2">
            <Sparkles className="w-4 h-4 text-amber-400 shrink-0" />
            <span className="font-mono">
              <strong>DEMO ANALYSIS:</strong> This result was loaded from a controlled cybersecurity training scenario. Do not present demo results as live forensic findings.
            </span>
          </div>
          <span className="hidden sm:inline-block px-2 py-0.5 rounded bg-amber-500/20 text-amber-300 font-mono text-[10px] uppercase">
            Synthetic Benchmark
          </span>
        </div>
      )}

      {/* Main Forensic Header Card */}
      <div className="p-6 sm:p-8 rounded-2xl bg-[#0b0f19]/95 border border-slate-800 shadow-[0_0_30px_rgba(0,0,0,0.5)]">
        <div className="flex flex-col md:flex-row md:items-center justify-between pb-6 border-b border-slate-800/80 gap-4">
          <div>
            <div className="flex items-center space-x-2 mb-2">
              <span className="px-2.5 py-0.5 rounded-md text-[11px] font-mono font-semibold bg-slate-900 border border-slate-700 text-slate-300">
                {result.contentType.toUpperCase()} INSPECTION
              </span>
              <span className="px-2.5 py-0.5 rounded-md text-[11px] font-mono font-semibold bg-cyan-950/60 border border-cyan-700/50 text-cyan-300">
                {result.platform}
              </span>
              {result.isCloudAnalysis ? (
                <span className="px-2 py-0.5 rounded text-[10px] font-mono bg-blue-500/10 text-blue-300 border border-blue-500/30">
                  Cloud Neural Pass
                </span>
              ) : (
                <span className="px-2 py-0.5 rounded text-[10px] font-mono bg-slate-800 text-slate-400 border border-slate-700">
                  Local Heuristics
                </span>
              )}
            </div>

            <h2 className="text-xl sm:text-2xl font-black text-white tracking-tight break-all">
              {result.targetSummary}
            </h2>
            <p className="text-xs text-slate-400 font-mono mt-1">
              Inspection ID: {result.id} • {new Date(result.timestamp).toLocaleString()}
            </p>
          </div>

          {/* Quick actions */}
          <div className="flex items-center space-x-2 shrink-0">
            <button
              onClick={handleCopyReport}
              className="flex items-center space-x-1.5 px-3 py-2 rounded-xl text-xs font-medium text-slate-300 bg-slate-900 hover:bg-slate-800 border border-slate-800 hover:border-slate-700 transition-all cursor-pointer"
              title="Copy text summary"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied' : 'Copy Report'}</span>
            </button>
            <button
              onClick={handlePrint}
              className="p-2 rounded-xl text-slate-300 bg-slate-900 hover:bg-slate-800 border border-slate-800 hover:border-slate-700 transition-all cursor-pointer"
              title="Print report"
            >
              <Printer className="w-4 h-4" />
            </button>
            <button
              onClick={onReset}
              className="flex items-center space-x-1.5 px-3.5 py-2 rounded-xl text-xs font-bold text-slate-950 bg-cyan-400 hover:bg-cyan-300 transition-all cursor-pointer"
            >
              <RotateCcw className="w-3.5 h-3.5" />
              <span>New Scan</span>
            </button>
          </div>
        </div>

        {/* Top Grid: Large Risk Meter + Prominent Category Summary */}
        <div className="mt-6 grid grid-cols-1 md:grid-cols-12 gap-6 items-center">
          <div className="md:col-span-5">
            <RiskMeter
              score={result.riskScore}
              level={result.riskLevel}
              verdictLabel={result.verdictLabel}
            />
          </div>

          <div className="md:col-span-7 space-y-4">
            {/* Primary Category Banner */}
            <div className="p-4 rounded-xl bg-slate-900/60 border border-slate-800">
              <span className="text-[11px] font-mono text-slate-400 uppercase tracking-wider block mb-1 font-semibold">
                Threat Classification:
              </span>
              <div className="flex items-center space-x-2.5">
                <span className="text-xl sm:text-2xl font-black text-white">
                  {result.category}
                </span>
                <span className="px-2 py-0.5 rounded text-xs font-mono bg-cyan-500/10 text-cyan-300 border border-cyan-500/30">
                  Confidence: {Math.round(result.confidence * 100)}%
                </span>
              </div>
              <p className="mt-2 text-xs text-slate-300 leading-relaxed">
                {result.explanation.whyFlaggedSummary}
              </p>
            </div>

            {/* Quick Signal Score Breakdown Bars */}
            {result.signalBreakdown && result.signalBreakdown.length > 0 && (
              <div className="p-4 rounded-xl bg-slate-900/40 border border-slate-800/80 space-y-2.5">
                <span className="text-[11px] font-mono text-slate-400 uppercase tracking-wider block font-semibold">
                  Signal Breakdown:
                </span>
                <div className="space-y-2">
                  {result.signalBreakdown.map((sig, idx) => (
                    <div key={idx} className="space-y-1">
                      <div className="flex justify-between text-xs">
                        <span className="text-slate-300 font-medium">{sig.name}</span>
                        <span className="text-slate-400 font-mono">
                          {sig.note ? sig.note : `${sig.score}% risk`}
                        </span>
                      </div>
                      <div className="w-full bg-slate-800 rounded-full h-1.5 overflow-hidden">
                        <div
                          className={`h-full rounded-full ${
                            sig.score >= 70
                              ? 'bg-rose-500'
                              : sig.score >= 40
                              ? 'bg-amber-500'
                              : 'bg-emerald-500'
                          }`}
                          style={{ width: `${sig.score}%` }}
                        />
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            )}
          </div>
        </div>
      </div>

      {/* Visual Forensic Heatmap if image or screenshot */}
      {(result.contentType === 'image' || result.contentType === 'screenshot') && uploadedImageUrl && (
        <HeatmapViewer
          imageUrl={uploadedImageUrl}
          markers={result.forensicMarkers || []}
          title={result.contentType === 'screenshot' ? 'Screenshot Layer Deconstruction' : 'Visual Forensics & Heatmap'}
        />
      )}

      {/* Screenshot Decomposition Component Breakdown (Section 13) */}
      {result.screenshotComponents && (
        <div className="p-6 rounded-2xl bg-slate-950/80 border border-slate-800 space-y-4">
          <div className="flex items-center justify-between pb-3 border-b border-slate-800">
            <h3 className="text-sm font-bold font-mono text-slate-200 uppercase tracking-wider flex items-center space-x-2">
              <Layers className="w-4 h-4 text-amber-400" />
              <span>Screenshot Decomposition Breakdown</span>
            </h3>
            <span className="text-xs text-slate-500 font-mono">Multi-Layer Extraction</span>
          </div>

          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
            <div className="p-3 rounded-xl bg-slate-900 border border-slate-800 text-center">
              <span className="text-[11px] font-mono text-slate-400 block mb-1">Message Detected</span>
              <span className={`text-xs font-bold font-mono ${result.screenshotComponents.messageDetected ? 'text-emerald-400' : 'text-slate-500'}`}>
                {result.screenshotComponents.messageDetected ? '✓ YES' : 'NO'}
              </span>
            </div>
            <div className="p-3 rounded-xl bg-slate-900 border border-slate-800 text-center">
              <span className="text-[11px] font-mono text-slate-400 block mb-1">Link Detected</span>
              <span className={`text-xs font-bold font-mono ${result.screenshotComponents.linkDetected ? 'text-rose-400' : 'text-slate-500'}`}>
                {result.screenshotComponents.linkDetected ? '⚠️ YES' : 'NO'}
              </span>
            </div>
            <div className="p-3 rounded-xl bg-slate-900 border border-slate-800 text-center">
              <span className="text-[11px] font-mono text-slate-400 block mb-1">Image Detected</span>
              <span className={`text-xs font-bold font-mono ${result.screenshotComponents.imageDetected ? 'text-emerald-400' : 'text-slate-500'}`}>
                {result.screenshotComponents.imageDetected ? '✓ YES' : 'NO'}
              </span>
            </div>
            <div className="p-3 rounded-xl bg-slate-900 border border-slate-800 text-center">
              <span className="text-[11px] font-mono text-slate-400 block mb-1">Profile Info</span>
              <span className={`text-xs font-bold font-mono ${result.screenshotComponents.profileInfoDetected ? 'text-cyan-400' : 'text-slate-500'}`}>
                {result.screenshotComponents.profileInfoDetected ? '✓ DETECTED' : 'NOT FOUND'}
              </span>
            </div>
          </div>

          {result.screenshotComponents.extractedUrls && result.screenshotComponents.extractedUrls.length > 0 && (
            <div className="p-3 rounded-lg bg-slate-900/60 border border-slate-800 text-xs">
              <span className="text-slate-400 font-mono block mb-1">Extracted Hyperlinks:</span>
              {result.screenshotComponents.extractedUrls.map((u, i) => (
                <span key={i} className="text-cyan-400 font-mono break-all block">
                  {u}
                </span>
              ))}
            </div>
          )}
        </div>
      )}

      {/* QR Destination Card (Section 14) */}
      {result.qrDestination && (
        <div className="p-5 rounded-2xl bg-emerald-950/30 border border-emerald-500/30 space-y-3">
          <div className="flex items-center justify-between">
            <span className="text-xs font-mono uppercase tracking-wider text-emerald-300 font-bold">
              Decoded QR Matrix Destination:
            </span>
            <span className="text-[11px] text-slate-400 font-mono">Quishing Security Screen</span>
          </div>

          <div className="p-3 rounded-lg bg-black/60 border border-slate-800 font-mono text-xs sm:text-sm text-cyan-300 break-all select-all">
            {result.qrDestination}
          </div>

          <div className="flex items-center space-x-3 pt-2">
            <a
              href={result.qrDestination.startsWith('http') ? result.qrDestination : '#'}
              target="_blank"
              rel="noopener noreferrer"
              className="inline-flex items-center space-x-1.5 px-3 py-1.5 rounded-lg text-xs font-medium text-amber-300 bg-amber-950/40 hover:bg-amber-950/60 border border-amber-500/30 transition-all"
            >
              <span>Open Only If Safe</span>
              <ExternalLink className="w-3.5 h-3.5" />
            </a>
            <span className="text-[11px] text-slate-400">
              Scam Shield never navigates to QR codes automatically.
            </span>
          </div>
        </div>
      )}

      {/* Media Model Notice (Section 15) */}
      {result.mediaNote && (
        <div className="p-4 rounded-xl bg-slate-900 border border-rose-500/40 text-xs text-slate-300 flex items-start space-x-3">
          <Info className="w-5 h-5 text-rose-400 shrink-0 mt-0.5" />
          <div>
            <span className="font-bold text-white block mb-0.5">Media Model Scope:</span>
            {result.mediaNote} Full frame-by-frame deepfake audio/video neural engines will be activated in upcoming model builds.
          </div>
        </div>
      )}

      {/* Section 18: WHY WE FLAGGED THIS */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        <div className="p-6 rounded-2xl bg-[#0b0f19]/90 border border-slate-800 space-y-4">
          <h3 className="text-sm font-bold font-mono text-white uppercase tracking-wider flex items-center space-x-2">
            <span className="w-2 h-2 rounded-full bg-cyan-400" />
            <span>What We Detected</span>
          </h3>

          <ul className="space-y-2.5">
            {result.explanation.whatWeDetected.map((item, idx) => (
              <li key={idx} className="flex items-start space-x-2 text-xs sm:text-sm text-slate-300">
                <ChevronRight className="w-4 h-4 text-cyan-400 shrink-0 mt-0.5" />
                <span>{item}</span>
              </li>
            ))}
          </ul>
        </div>

        <div className="p-6 rounded-2xl bg-[#0b0f19]/90 border border-slate-800 space-y-4">
          <h3 className="text-sm font-bold font-mono text-white uppercase tracking-wider flex items-center space-x-2">
            <span className="w-2 h-2 rounded-full bg-blue-400" />
            <span>Why It Matters</span>
          </h3>

          <p className="text-xs sm:text-sm text-slate-300 leading-relaxed">
            {result.explanation.whyItMatters}
          </p>

          <div className="pt-2 border-t border-slate-800/80">
            <span className="text-[11px] font-mono text-slate-500">
              Confidence Factor: {(result.confidence * 100).toFixed(0)}% (probabilistic assessment)
            </span>
          </div>
        </div>
      </div>

      {/* Threat Signals List with Severity Badges */}
      <div className="p-6 rounded-2xl bg-[#0b0f19]/90 border border-slate-800 space-y-4">
        <div className="flex items-center justify-between pb-3 border-b border-slate-800">
          <h3 className="text-sm font-bold font-mono text-white uppercase tracking-wider">
            Identified Threat Signals ({result.threatSignals.length})
          </h3>
          <span className="text-xs text-slate-500 font-mono">Prioritized by Impact</span>
        </div>

        <div className="space-y-3">
          {result.threatSignals.map((signal) => {
            const severityColor =
              signal.severity === 'high'
                ? 'bg-rose-950/60 border-rose-500/50 text-rose-300'
                : signal.severity === 'medium'
                ? 'bg-amber-950/60 border-amber-500/50 text-amber-300'
                : signal.severity === 'low'
                ? 'bg-yellow-950/60 border-yellow-500/50 text-yellow-300'
                : 'bg-blue-950/60 border-blue-500/50 text-blue-300';

            const dotColor =
              signal.severity === 'high'
                ? 'bg-rose-400'
                : signal.severity === 'medium'
                ? 'bg-amber-400'
                : signal.severity === 'low'
                ? 'bg-yellow-400'
                : 'bg-blue-400';

            return (
              <div
                key={signal.id}
                className="p-4 rounded-xl bg-slate-900/60 border border-slate-800/80 space-y-1.5"
              >
                <div className="flex items-center justify-between">
                  <div className="flex items-center space-x-2">
                    <span className={`w-2 h-2 rounded-full ${dotColor}`} />
                    <span className="text-sm font-bold text-white">{signal.title}</span>
                  </div>
                  <span
                    className={`px-2 py-0.5 rounded text-[10px] font-mono uppercase tracking-wider border font-bold ${severityColor}`}
                  >
                    {signal.severity}
                  </span>
                </div>
                <p className="text-xs text-slate-400 leading-relaxed pl-4">
                  {signal.description}
                </p>
              </div>
            );
          })}
        </div>
      </div>

      {/* Actionable Recommendations: WHAT YOU SHOULD DO */}
      <div className="p-6 sm:p-8 rounded-2xl bg-gradient-to-br from-cyan-950/30 to-blue-950/30 border border-cyan-500/30 shadow-[0_0_25px_rgba(6,182,212,0.1)] space-y-4">
        <h3 className="text-base font-extrabold text-white tracking-tight flex items-center space-x-2">
          <CheckCircle2 className="w-5 h-5 text-cyan-400" />
          <span>What You Should Do Next</span>
        </h3>

        <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
          {result.recommendations.map((rec, idx) => (
            <div
              key={idx}
              className="p-4 rounded-xl bg-slate-950/80 border border-cyan-950/80 space-y-2"
            >
              <span className="w-6 h-6 rounded-lg bg-cyan-500/10 text-cyan-400 font-mono text-xs font-bold flex items-center justify-center border border-cyan-500/20">
                0{idx + 1}
              </span>
              <p className="text-xs text-slate-300 leading-relaxed">{rec}</p>
            </div>
          ))}
        </div>
      </div>

    </div>
  );
};
